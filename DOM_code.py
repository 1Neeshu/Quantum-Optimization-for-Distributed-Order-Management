def locate_csv(required_keywords, excluded_keywords=()):
    required_keywords = [k.lower() for k in required_keywords]
    excluded_keywords = [k.lower() for k in excluded_keywords]

    matches = []
    for root in SEARCH_ROOTS:
        if not root.exists():
            continue
        try:
            for path in root.rglob("*.csv"):
                name = path.name.lower()
                if (
                    all(k in name for k in required_keywords)
                    and not any(k in name for k in excluded_keywords)
                ):
                    matches.append(path)
        except PermissionError:
            continue

    # if not matches:
    #     raise FileNotFoundError(
