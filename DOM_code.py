def expected_proxy_value(soft_bits):
    total = 0.0

    for index, row in focus.iterrows():
        diversion = float(soft_bits[index])
        total += (
            (1.0 - diversion) * float(row["default_proxy_Z"])
            + diversion * float(row["alt_proxy_Z"])
        )

    return total

def normalized_capacity_violations(soft_bits):
    dock_load, case_load, pallet_load = proxy_capacity_loads(
        soft_bits
    )

    dock_violation = {}
    case_violation = {}
    pallet_violation = {}

    for key, used in dock_load.items():
        capacity = effective_order_capacity(*key)
        excess = max(0.0, used - capacity)
        dock_violation[key] = excess / max(capacity, 1.0)

    for key, used in case_load.items():
        capacity = float(case_pick_capacity.get(key, 0.0))
        excess = max(0.0, used - capacity)
        case_violation[key] = excess / max(capacity, 1.0)

    for key, used in pallet_load.items():
        capacity = float(pallet_pick_capacity.get(key, 0.0))
        excess = max(0.0, used - capacity)
        pallet_violation[key] = excess / max(capacity, 1.0)

    return (
        dock_violation,
        case_violation,
        pallet_violation,
    )

def augmented_lagrangian_penalty(
    violations,
    multipliers,
    mu,
):
    total = 0.0

    for key, violation in violations.items():
        multiplier = float(multipliers.get(key, 0.0))
        total += (
            multiplier * violation
            + 0.5 * mu * violation**2
        )

    return total

def master_loss(
    theta,
    alpha,
    dock_multipliers,
    case_multipliers,
    pallet_multipliers,
):
    correlations = correlator_values(theta)
    soft_bits = soft_bits_from_correlations(
        correlations,
        alpha,
    )

    normalized_value_term = (
        -expected_proxy_value(soft_bits)
        / OBJECTIVE_SCALE
    )

    dock_v, case_v, pallet_v = (
        normalized_capacity_violations(soft_bits)
    )

    capacity_term = (
        augmented_lagrangian_penalty(
            dock_v,
            dock_multipliers,
            AL_MU_DOCK,
        )
        + augmented_lagrangian_penalty(
            case_v,
            case_multipliers,
            AL_MU_CASE,
        )
        + augmented_lagrangian_penalty(
            pallet_v,
            pallet_multipliers,
            AL_MU_PALLET,
        )
    )

    return normalized_value_term + capacity_term

print("Objective normalization scale:", OBJECTIVE_SCALE)


from scipy.optimize import minimize

def update_multipliers(multipliers, violations, mu):
    for key, violation in violations.items():
        multipliers[key] = max(
            0.0,
            float(multipliers.get(key, 0.0))
            + mu * float(violation),
        )

def maximum_violation(*violation_dictionaries):
    values = [
        float(value)
        for dictionary in violation_dictionaries
        for value in dictionary.values()
    ]
    return max(values, default=0.0)

def run_single_pce_restart(restart_index, seed):
    rng = np.random.default_rng(seed)
    theta = rng.uniform(
        -np.pi,
        np.pi,
        size=ansatz.num_parameters,
    )

    alpha_initial = (
        ALPHA_C
        * N_QUBITS ** (PCE_DEGREE / 2)
    )
    alpha = float(alpha_initial)

    dock_multipliers = defaultdict(float)
    case_multipliers = defaultdict(float)
    pallet_multipliers = defaultdict(float)

    best_record = None
    history_rows = []
    seen_bits = set()
    stall = 0

    for outer in range(1, N_OUTER + 1):
        alpha_used = alpha

        optimization = minimize(
            lambda parameters: master_loss(
                parameters,
                alpha_used,
                dock_multipliers,
                case_multipliers,
                pallet_multipliers,
            ),
            theta,
            method="COBYLA",
            options={
                "maxiter": COBYLA_MAXITER,
                "tol": COBYLA_TOL,
            },
        )

        theta = np.asarray(
            optimization.x,
            dtype=float,
        )

        correlations = correlator_values(theta)
        soft_bits = soft_bits_from_correlations(
            correlations,
            alpha_used,
        )
        bits = hard_bits_from_correlations(correlations)
        recourse = solve_recourse(bits)

        dock_v, case_v, pallet_v = (
            normalized_capacity_violations(soft_bits)
        )
        max_violation = maximum_violation(
            dock_v,
            case_v,
            pallet_v,
        )

        new_best = (
            best_record is None
            or recourse["Z"]
            > best_record["recourse"]["Z"]
            + NUMERICAL_TOLERANCE
        )

        if new_best:
            best_record = {
                "restart": restart_index,
                "seed": seed,
                "outer": outer,
                "theta": theta.copy(),
                "alpha": alpha_used,
                "alpha_initial": alpha_initial,
                "correlations": correlations.copy(),
                "soft_bits": soft_bits.copy(),
                "bits": bits,
                "recourse": recourse,
                "master_loss": float(optimization.fun),
            }
            stall = 0
        else:
            stall += 1

        repeated = bits in seen_bits
        seen_bits.add(bits)

        history_rows.append(
            {
                "restart": restart_index,
                "seed": seed,
                "outer": outer,
                "alpha": alpha_used,
                "master_loss": float(optimization.fun),
                "recourse_Z": recourse["Z"],
                "incumbent_Z": best_record["recourse"]["Z"],
                "max_normalized_violation": max_violation,
                "bits": "".join(map(str, bits)),
                "repeated_bits": repeated,
                "optimizer_success": bool(
                    optimization.success
                ),
                "optimizer_message": str(
                    optimization.message
                ),
                "function_evaluations": int(
                    optimization.nfev
                ),
            }
        )

        update_multipliers(
            dock_multipliers,
            dock_v,
            AL_MU_DOCK,
        )
        update_multipliers(
            case_multipliers,
            case_v,
            AL_MU_CASE,
        )
        update_multipliers(
            pallet_multipliers,
            pallet_v,
            AL_MU_PALLET,
        )

        if stall >= PATIENCE:
            break

        alpha *= ALPHA_GROWTH

        if repeated:
            theta = theta + rng.normal(
                0.0,
                0.03,
                size=theta.shape,
            )

    return best_record, pd.DataFrame(history_rows)

