def cases_per_pallet(line):
    for column in ["CasesPerPallet", "ProductCasesPerPallet", "cases_per_pallet"]:
        if column in line.index:
            value = pd.to_numeric(line[column], errors="coerce")
            if pd.notna(value) and float(value) > 0:
                return max(int(round(float(value))), 1)
    return 1

def get_unit_revenue(line):
    demand = float(line["OrderedQty_converted"])
    return float(line["Order_SKU_Revenue"]) / demand if demand > 0 else 0.0

def option_proxy_metrics(dc, pgi_date, zip_code, order_lines):
    line_rows = []
    total_demand = 0.0
    total_filled = 0.0
    fulfilled_revenue = 0.0
    case_picks = 0.0
    pallet_picks = 0.0

    for _, line in order_lines.iterrows():
        demand = max(float(line["OrderedQty_converted"]), 0.0)
        available = max(
            float(inventory.get((dc, line["MaterialNumber"], pgi_date), 0.0)),
            0.0,
        )
        filled = min(demand, available)
        cpp = cases_per_pallet(line)
        pallet_count = math.floor(filled / cpp)
        loose_count = filled - cpp * pallet_count
        unit_revenue = get_unit_revenue(line)

        total_demand += demand
        total_filled += filled
        fulfilled_revenue += unit_revenue * filled
        pallet_picks += pallet_count
        case_picks += loose_count

        line_rows.append(
            {
                "demand": demand,
                "filled": filled,
                "unit_revenue": unit_revenue,
            }
        )

    threshold_cases = math.ceil(
        FILL_THRESHOLD * total_demand - NUMERICAL_TOLERANCE
    )
    below_threshold = total_filled < threshold_cases

    shortfall_penalty = 0.0
    if below_threshold:
        for row_value in line_rows:
            shortfall_penalty += (
                PENALTY_RATE
                * row_value["unit_revenue"]
                * max(row_value["demand"] - row_value["filled"], 0.0)
            )

    shipping = (
        float(shipping_cost.get((dc, zip_code), 0.0))
        if total_filled > NUMERICAL_TOLERANCE
        else 0.0
    )

    return {
        "filled": total_filled,
        "demand": total_demand,
        "revenue": fulfilled_revenue,
        "penalty": shortfall_penalty,
        "shipping": shipping,
        "proxy_Z": fulfilled_revenue - shortfall_penalty - shipping,
        "case_picks": case_picks,
        "pallet_picks": pallet_picks,
        "served_proxy": float(total_filled > NUMERICAL_TOLERANCE),
    }

