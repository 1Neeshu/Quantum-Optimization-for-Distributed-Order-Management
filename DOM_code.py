def proxy_capacity_loads(values):

    dock_load = defaultdict(float)
    case_load = defaultdict(float)
    pallet_load = defaultdict(float)

    for index, row in focus.iterrows():
        diversion = float(values[index])
        stay = 1.0 - diversion

        default_key = (row["default_dc"], row["pgi"])
        alternate_key = (row["alt_dc"], row["pgi"])

        dock_load[default_key] += stay * row["default_served_proxy"]
        dock_load[alternate_key] += diversion * row["alt_served_proxy"]

        case_load[default_key] += stay * row["default_case_picks"]
        case_load[alternate_key] += diversion * row["alt_case_picks"]

        pallet_load[default_key] += stay * row["default_pallet_picks"]
        pallet_load[alternate_key] += diversion * row["alt_pallet_picks"]

    return dock_load, case_load, pallet_load

