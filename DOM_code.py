def build_contested_ranking(candidate_table):

    ranked = candidate_table.copy()
    group_keys = ["alt_dc", "pgi"]

    group_stats = (
        ranked.groupby(group_keys)
        .agg(
            competing_orders=("order_id", "count"),
            total_alt_case_picks=("alt_case_picks", "sum"),
            total_alt_pallet_picks=("alt_pallet_picks", "sum"),
            total_alt_served=("alt_served_proxy", "sum"),
        )
        .reset_index()
    )

    pressure_rows = []
    for _, group in group_stats.iterrows():
        key = (group["alt_dc"], group["pgi"])
        dock_cap = effective_order_capacity(*key)
        case_cap = float(case_pick_capacity.get(key, 0.0))
        pallet_cap = float(pallet_pick_capacity.get(key, 0.0))

        dock_pressure = group["total_alt_served"] / max(dock_cap, 1.0)
        case_pressure = group["total_alt_case_picks"] / max(case_cap, 1.0)
        pallet_pressure = group["total_alt_pallet_picks"] / max(pallet_cap, 1.0)

        pressure_rows.append(
            {
                "alt_dc": group["alt_dc"],
                "pgi": group["pgi"],
                "competing_orders": group["competing_orders"],
                "dock_pressure": dock_pressure,
                "case_pressure": case_pressure,
                "pallet_pressure": pallet_pressure,
                "resource_pressure": max(
                    dock_pressure,
                    case_pressure,
                    pallet_pressure,
                ),
            }
        )

    pressure_table = pd.DataFrame(pressure_rows)
    ranked = ranked.merge(
        pressure_table,
        on=group_keys,
        how="left",
    )

    ranked["contested_score"] = (
        ranked["resource_pressure"]
        * ranked["competing_orders"]
        * np.log1p(ranked["risk_score"].clip(lower=0.0))
    )

    return ranked.sort_values(
        [
            "contested_score",
            "resource_pressure",
            "competing_orders",
            "risk_score",
        ],
        ascending=[False, False, False, False],
    ).reset_index(drop=True)

def select_focus_batch(candidate_table, batch_size, mode):
    n_select = min(batch_size, len(candidate_table))

    if mode == "high_risk":
        selected = (
            candidate_table.sort_values(
                ["risk_score", "alt_proxy_Z", "alt_filled"],
                ascending=[False, False, False],
            )
            .head(n_select)
            .copy()
        )
    elif mode == "contested":
        ranked = build_contested_ranking(candidate_table)

        # Anchor on the single strongest shared alternate-DC/date conflict.
        leading_key = (
            ranked.iloc[0]["alt_dc"],
            ranked.iloc[0]["pgi"],
        )
        same_group = ranked[
            (ranked["alt_dc"] == leading_key[0])
            & (ranked["pgi"] == leading_key[1])
        ].copy()

        selected = same_group.head(n_select).copy()


        if len(selected) < n_select:
            remaining = ranked[
                ~ranked["order_id"].isin(selected["order_id"])
            ].head(n_select - len(selected))
            selected = pd.concat(
                [selected, remaining],
                ignore_index=True,
            )
    else:
        raise ValueError(
            "BATCH_MODE must be 'high_risk' or 'contested'."
        )

    return selected.reset_index(drop=True)

