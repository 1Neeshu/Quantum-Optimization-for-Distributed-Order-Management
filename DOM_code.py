def minimum_pce_qubits(n_variables, degree=2):
    if degree != 2:
        raise NotImplementedError(
            "This notebook only implements degree-2 PCE."
        )
    if n_variables <= 0:
        raise ValueError("At least one variable is required.")

    n_qubits = 2
    while 3 * math.comb(n_qubits, 2) < n_variables:
        n_qubits += 1
    return n_qubits

def pair_pauli_label(n_qubits, qubit_i, qubit_j, axis):
    chars = ["I"] * n_qubits
    chars[n_qubits - 1 - qubit_i] = axis
    chars[n_qubits - 1 - qubit_j] = axis
    return "".join(chars)

