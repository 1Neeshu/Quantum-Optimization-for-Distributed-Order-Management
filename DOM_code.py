def normalize_identifier(value):
    if pd.isna(value):
        return None
    text = str(value).strip()
    if re.fullmatch(r"-?\d+\.0+", text):
        text = text.split(".")[0]
    return text

def normalize_zip(value):
    if pd.isna(value):
        return None
    text = normalize_identifier(value)
    digits = re.sub(r"\D", "", text or "")
    return digits.zfill(5) if digits else None

def parse_date_column(dataframe, column, label):

    parsed = pd.to_datetime(
        dataframe[column],
        format="%Y-%m-%d",
        errors="coerce",
    )

    unresolved = parsed.isna() & dataframe[column].notna()
    if unresolved.any():
        try:
            fallback = pd.to_datetime(
                dataframe.loc[unresolved, column],
                format="mixed",
                errors="coerce",
            )
        except (TypeError, ValueError):
            fallback = pd.to_datetime(
                dataframe.loc[unresolved, column],
                errors="coerce",
            )
        parsed.loc[unresolved] = fallback

    parsed = parsed.dt.normalize()
    invalid = parsed.isna() & dataframe[column].notna()
    if invalid.any():
        print(f"Warning: dropping {int(invalid.sum())} invalid dates from {label}.")
    return parsed

