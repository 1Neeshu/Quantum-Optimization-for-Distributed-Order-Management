def complement_bits(bits):
    return tuple(
        1 - bit
        for bit in validate_bits(bits)
    )

def one_flip_postprocess(initial_bits):
    current_bits = validate_bits(initial_bits)
    current_result = solve_recourse(current_bits)

    trace = [
        {
            "step": 0,
            "move": "initial quantum decode",
            "bits": "".join(map(str, current_bits)),
            "Z": current_result["Z"],
        }
    ]

    complemented = complement_bits(current_bits)
    complement_result = solve_recourse(complemented)

    if (
        complement_result["Z"]
        > current_result["Z"] + NUMERICAL_TOLERANCE
    ):
        current_bits = complemented
        current_result = complement_result
        trace.append(
            {
                "step": len(trace),
                "move": "full complement",
                "bits": "".join(map(str, current_bits)),
                "Z": current_result["Z"],
            }
        )

    improved = True

    while improved:
        improved = False
        best_neighbor_bits = current_bits
        best_neighbor_result = current_result
        best_flip = None

        for variable_index in range(len(current_bits)):
            trial = list(current_bits)
            trial[variable_index] = (
                1 - trial[variable_index]
            )
            trial = tuple(trial)
            trial_result = solve_recourse(trial)

            if (
                trial_result["Z"]
                > best_neighbor_result["Z"]
                + NUMERICAL_TOLERANCE
            ):
                best_neighbor_bits = trial
                best_neighbor_result = trial_result
                best_flip = variable_index

        if best_flip is not None:
            current_bits = best_neighbor_bits
            current_result = best_neighbor_result
            improved = True

            trace.append(
                {
                    "step": len(trace),
                    "move": (
                        f"flip variable {best_flip} "
                        f"(order {order_ids[best_flip]})"
                    ),
                    "bits": "".join(map(str, current_bits)),
                    "Z": current_result["Z"],
                }
            )

    return current_result, pd.DataFrame(trace)

